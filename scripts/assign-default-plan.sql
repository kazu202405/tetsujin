-- ============================================================
-- 未割当の会員に既定プラン（個人・月1,650円）を割り当てる
-- ============================================================
-- 依頼主判断（川原さん 2026-08-25）:
--   「法人は少ないので、空いている人は一旦すべて個人で入れてよい。
--     会員の状態は川原さんが管理画面で確認しながら見ていく」
--
-- ∴ membership_type が空欄で放置されていた276名を monthly_1650 に寄せ、
--   法人だと分かった人だけ川原さんが管理画面で monthly_2500 に上げる。
--
-- 🔴 安い側に倒す理由:
--   個人の人に法人料金(月2,500)を請求するとクレームと解約になる。
--   逆は「取りそこねる」だけで済む。差額は月850円。
--   入会フォームの3項目（立場・業種・地域）が埋まれば自然に精度が上がる。
--
-- 🔴 billing_starts_on はここでは触らない。
--   373名に設定済み・68名未設定という状態を、プラン割当と混ぜると
--   どちらが原因で請求が始まった/始まらないのかが追えなくなる。
--
-- 実行順: ① 確認 → ② 更新 → ③ 検算
-- ============================================================


-- ------------------------------------------------------------
-- ① 実行前の確認（これだけ先に流して件数を見る）
-- ------------------------------------------------------------
SELECT
  COALESCE(billing_plan_code, '(未割当)') AS plan,
  COUNT(*)                                AS 人数
FROM public.members
WHERE is_withdrawn = FALSE
GROUP BY 1
ORDER BY 2 DESC;

-- 今回書き換わる対象だけを数える
SELECT COUNT(*) AS これから個人にする人数
FROM public.members
WHERE is_withdrawn   = FALSE
  AND billing_exempt = FALSE      -- 免除者（五島・川原）は対象外
  AND billing_plan_code IS NULL;


-- ------------------------------------------------------------
-- ② 更新
-- ------------------------------------------------------------
-- 対象は「在籍」かつ「免除でない」かつ「プラン未設定」の人だけ。
-- 既に monthly_2500 / monthly_2750 が入っている人には触れない。
UPDATE public.members
   SET billing_plan_code = 'monthly_1650'
 WHERE is_withdrawn   = FALSE
   AND billing_exempt = FALSE
   AND billing_plan_code IS NULL;


-- ------------------------------------------------------------
-- ③ 検算
-- ------------------------------------------------------------
-- 未割当が0になり、monthly_1650 が (元の129 + 276) 前後になっていること。
-- 免除2名が未割当のまま残るのが正しい（免除は billing_plan_code では表さない）。
SELECT
  COALESCE(billing_plan_code, '(未割当)') AS plan,
  billing_exempt                          AS 免除,
  COUNT(*)                                AS 人数
FROM public.members
WHERE is_withdrawn = FALSE
GROUP BY 1, 2
ORDER BY 3 DESC;
